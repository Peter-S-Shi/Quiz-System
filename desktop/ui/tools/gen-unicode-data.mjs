// Generates web/src/task-domains/unicode/data.js: the project-controlled, version-pinned Unicode tables behind
// typing-compare/1 (ADR 0004 section 8.3). It reads the Unicode Character Database files of ONE pinned version from
// tools/ucd-cache/ (not committed; download URLs below) and records the SHA-256 of every input in the output, so the
// committed data file is reproducible and auditable. Nothing here, and nothing that uses the output, consults the
// host's ICU / Intl.Segmenter / String.prototype.normalize.
//
//   node tools/gen-unicode-data.mjs
//
// Inputs (https://www.unicode.org/Public/<VERSION>/ucd/):
//   auxiliary/GraphemeBreakProperty.txt, emoji/emoji-data.txt, DerivedCoreProperties.txt (InCB),
//   UnicodeData.txt, DerivedNormalizationProps.txt (Full_Composition_Exclusion)
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const VERSION = '16.0.0';
const here = path.dirname(fileURLToPath(import.meta.url));
const cache = path.join(here, 'ucd-cache');
const out = path.join(here, '..', 'web', 'src', 'task-domains', 'unicode', 'data.js');
const FILES = ['GraphemeBreakProperty.txt', 'emoji-data.txt', 'DerivedCoreProperties.txt', 'UnicodeData.txt', 'DerivedNormalizationProps.txt'];

const read = (f) => fs.readFileSync(path.join(cache, f));
const sha = Object.fromEntries(FILES.map((f) => [f, crypto.createHash('sha256').update(read(f)).digest('hex')]));
const lines = (f) => read(f).toString('utf8').split('\n');

function propertyRanges(file, wanted, column = 1) {
  const ranges = [];
  for (const raw of lines(file)) {
    const line = raw.split('#')[0].trim();
    if (!line) continue;
    const parts = line.split(';').map((x) => x.trim());
    const [range, ...rest] = parts;
    const [a, b = a] = range.split('..').map((h) => parseInt(h, 16));
    const value = column === 1 ? rest[0] : rest.join(';');
    const key = wanted(value, rest);
    if (key !== undefined) ranges.push([a, b, key]);
  }
  return ranges.sort((x, y) => x[0] - y[0]);
}

const GCB = ['CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator', 'Prepend', 'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT'];
const gcb = propertyRanges('GraphemeBreakProperty.txt', (v) => (GCB.includes(v) ? GCB.indexOf(v) + 1 : undefined));
const ep = propertyRanges('emoji-data.txt', (v) => (v === 'Extended_Pictographic' ? 1 : undefined));
const INCB = ['Linker', 'Consonant', 'Extend'];
const incb = [];
for (const raw of lines('DerivedCoreProperties.txt')) {
  const line = raw.split('#')[0].trim();
  const m = /^([0-9A-F.]+)\s*;\s*InCB\s*;\s*(\w+)$/.exec(line);
  if (!m || !INCB.includes(m[2])) continue;
  const [a, b = a] = m[1].split('..').map((h) => parseInt(h, 16));
  incb.push([a, b, INCB.indexOf(m[2]) + 1]);
}
incb.sort((x, y) => x[0] - y[0]);

const fce = new Set();
for (const raw of lines('DerivedNormalizationProps.txt')) {
  const line = raw.split('#')[0].trim();
  const m = /^([0-9A-F.]+)\s*;\s*Full_Composition_Exclusion$/.exec(line);
  if (!m) continue;
  const [a, b = a] = m[1].split('..').map((h) => parseInt(h, 16));
  for (let c = a; c <= b; c += 1) fce.add(c);
}

const ccc = [];
const decomp = []; // [cp, d1, d2?] canonical single-step mappings
const compose = []; // [first, second, composite]
let rangeStart = null;
for (const raw of lines('UnicodeData.txt')) {
  if (!raw) continue;
  const f = raw.split(';');
  const cp = parseInt(f[0], 16);
  const name = f[1];
  const cls = parseInt(f[3], 10);
  if (name.endsWith(', First>')) { rangeStart = { cp, cls }; continue; }
  if (name.endsWith(', Last>')) {
    if (rangeStart.cls) ccc.push([rangeStart.cp, cp, rangeStart.cls]);
    rangeStart = null;
    continue;
  }
  if (cls) ccc.push([cp, cp, cls]);
  const d = f[5];
  if (d && !d.startsWith('<')) {
    const parts = d.split(' ').map((h) => parseInt(h, 16));
    decomp.push([cp, ...parts]);
    if (parts.length === 2 && !fce.has(cp)) compose.push([parts[0], parts[1], cp]);
  }
}
// merge adjacent ccc entries with the same class
const cccMerged = [];
for (const r of ccc.sort((x, y) => x[0] - y[0])) {
  const last = cccMerged[cccMerged.length - 1];
  if (last && last[2] === r[2] && last[1] + 1 === r[0]) last[1] = r[1];
  else cccMerged.push([...r]);
}
compose.sort((x, y) => x[0] - y[0] || x[1] - y[1]);

const flat = (rows) => rows.flat().join(',');
const body = `// GENERATED by tools/gen-unicode-data.mjs from the Unicode Character Database ${VERSION}. Do not edit.
// This file IS the pinned truth of typing-compare/1 (ADR 0004 section 8.3): the host's Unicode behavior never enters.
export const UNICODE_VERSION = '${VERSION}';
export const SOURCE_SHA256 = ${JSON.stringify(sha, null, 2)};
// flat [start, end, class] triples; GCB classes are 1-based indexes into GCB_CLASSES
export const GCB_CLASSES = ${JSON.stringify(GCB)};
export const GCB_RANGES = [${flat(gcb)}];
export const EXTENDED_PICTOGRAPHIC_RANGES = [${flat(ep)}];
export const INCB_CLASSES = ${JSON.stringify(INCB)};
export const INCB_RANGES = [${flat(incb)}];
export const CCC_RANGES = [${flat(cccMerged)}];
// canonical single-step decompositions: [cp, d1] or [cp, d1, d2], concatenated with a leading length
export const DECOMPOSITIONS = [${decomp.map((r) => `${r.length - 1},${r.join(',')}`).join(',')}];
// primary composites: [first, second, composite] triples
export const COMPOSITIONS = [${flat(compose)}];
`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, body, 'utf8');
console.log(`wrote ${path.relative(path.join(here, '..'), out)} (${body.length} bytes): gcb ${gcb.length}, ep ${ep.length}, incb ${incb.length}, ccc ${cccMerged.length}, decomp ${decomp.length}, compose ${compose.length}`);
